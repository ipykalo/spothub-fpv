export type CountryCode = (typeof COUNTRY_CODES)[number];

/** Whether a string is one of `COUNTRY_CODES`, exactly. */
export function isCountryCode(value: string): value is CountryCode {
  return (COUNTRY_CODES as readonly string[]).includes(value);
}

/** One country code, in any case. */
export const countryCodeSchema = z
  .string()
  .trim()
  .toUpperCase()
  .pipe(z.enum(COUNTRY_CODES, { error: 'Choose a country from the list' }));

let names: Intl.DisplayNames | null = null;

/** "Russia" for `RU`, from the runtime's own data; the code itself when it has none. */
export function countryName(code: string): string {
  try {
    names ??= new Intl.DisplayNames(['en'], { type: 'region' });
    return names.of(code) ?? code;
  } catch {
    return code;
  }
}
